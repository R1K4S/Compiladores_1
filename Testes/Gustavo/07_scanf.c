int main() {
    int    n;
    float  f;
    char   c;

    /* Le um inteiro */
    scanf("%d", n);
    printf("inteiro lido: %d\n", n);

    /* Le um float */
    scanf("%f", f);
    printf("float lido: %f\n", f);

    /* Le um char */
    scanf("%c", c);
    printf("char lido: %c\n", c);

    return 0;
}
